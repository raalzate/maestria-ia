export const FONT_CHARS = Object.keys(GLYPHS).join('');
export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** Celda en la hoja: 6x8 (1 px de separación). */
export const CELL_W = 6;
export const CELL_H = 8;

export interface FontStyle {
  color: number;
  shadow?: number;
  outline?: number;
}

/** Hoja de fuente para RetroFont de Phaser. Una fila por carácter, todos en línea. */
export function buildFontSheet(style: FontStyle): { pixmap: Pixmap; charsPerRow: number } {
  const chars = FONT_CHARS;
  const charsPerRow = chars.length;
  const pad = style.outline !== undefined || style.shadow !== undefined ? 1 : 0;
  const cellW = CELL_W + pad * 2;
  const cellH = CELL_H + pad * 2;
  const pm = new Pixmap(cellW * charsPerRow, cellH);
  const fill = hexToRgba(style.color);
  for (let i = 0; i < chars.length; i++) {
    const glyph = GLYPHS[chars[i]];
    const ox = i * cellW + pad;
    const oy = pad;
    if (style.shadow !== undefined) drawGlyph(pm, glyph, ox + 1, oy + 1, hexToRgba(style.shadow));
    drawGlyph(pm, glyph, ox, oy, fill);
  }
  if (style.outline !== undefined) {
    // contorno por celda para no fusionar glifos vecinos
    const out = hexToRgba(style.outline);
    const src = pm.clone();
    for (let i = 0; i < chars.length; i++) {
      const cx0 = i * cellW;
      for (let y = 0; y < cellH; y++) {
        for (let x = cx0; x < cx0 + cellW; x++) {
          if (src.alpha(x, y) > 0) continue;
          const nb =
            (x + 1 < cx0 + cellW && src.alpha(x + 1, y) > 0) ||
            (x - 1 >= cx0 && src.alpha(x - 1, y) > 0) ||
            src.alpha(x, y + 1) > 0 ||
            src.alpha(x, y - 1) > 0;
          if (nb) pm.set(x, y, out);
        }
      }
    }
  }
  return { pixmap: pm, charsPerRow };
}

export function drawGlyph(pm: Pixmap, glyph: string[], ox: number, oy: number, c: Rgba): void {
  for (let y = 0; y < GLYPH_H; y++) {
    for (let x = 0; x < GLYPH_W; x++) {
      if (glyph[y][x] === '#') pm.set(ox + x, oy + y, c);
    }
  }
}

/** Dibuja texto directamente en una pixmap (para logotipos y retratos). */
export function drawText(pm: Pixmap, text: string, x: number, y: number, c: Rgba, scale = 1, spacing = 1): void {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch] ?? GLYPHS['?'];
    for (let gy = 0; gy < GLYPH_H; gy++) {
      for (let gx = 0; gx < GLYPH_W; gx++) {
        if (glyph[gy][gx] === '#') pm.rect(cx + gx * scale, y + gy * scale, scale, scale, c);
      }
    }
    cx += (GLYPH_W + spacing) * scale;
  }
}

export function textWidth(text: string, scale = 1, spacing = 1): number {
  return text.length * (GLYPH_W + spacing) * scale - spacing * scale;
}

export function fontCellSize(style: FontStyle): { w: number; h: number } {
  const pad = style.outline !== undefined || style.shadow !== undefined ? 1 : 0;
  return { w: CELL_W + pad * 2, h: CELL_H + pad * 2 };
}
